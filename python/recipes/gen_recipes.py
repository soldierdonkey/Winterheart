#!/usr/bin/env python3
"""Generate the recipe and item-tag JSON in datapacks/winterheart_recipes/.

Edit the tables below, run this script, then /reload in game:

    python3 python/recipes/gen_recipes.py

Every file this script writes carries a "__comment__" marker naming it. On each run it
first deletes the files with its marker, so removed entries don't linger. Files without
the marker (pack.mcmeta, files from other generators) are left alone.

TACZ gunsmith recipes are generated by python/tacz/gen_gunsmith_recipes.py instead.
"""
import json
from pathlib import Path

PACK = Path(__file__).resolve().parents[2] / "datapacks/winterheart_recipes"
MARKER = "Generated by python/recipes/gen_recipes.py. Edit the script, not this file."

# Recipes to switch off. A file at the same ID with a forge:false condition replaces the original.
DISABLED = [
    # Stone tool recipes from Gore Edition, replaced by our string-bound stone tools
    "gore_edition:exarrack_can_craft_stone_axe",
    "gore_edition:exarrack_can_craft_stone_axe_two",
    "gore_edition:exarrack_can_craft_stone_hoe",
    "gore_edition:exarrack_can_craft_stone_hoe_two",
    "gore_edition:exarrack_can_craft_stone_pickaxe",
    "gore_edition:exarrack_can_craft_stone_shovel",
    # Gunpowder only comes from saltpeter
    "tacz:gunpowder",
    # Moss clumps smelt into sponge instead
    "immersive_weathering:green_dye_from_moss_clump",
]

# ---------------------------------------------------------------- equipment
STRING = "#notreepunching:string"
LEATHER = "minecraft:leather"
HIGH_TIERS = [("iron", "minecraft:iron_ingot"), ("golden", "minecraft:gold_ingot"), ("diamond", "minecraft:diamond")]

# Armor needs lining (L) inside the material (M)
ARMOR_TIERS = [("leather", LEATHER, STRING)] + [(t, m, LEATHER) for t, m in HIGH_TIERS]
ARMOR_PATTERNS = {
    "helmet": ["MMM", "MLM"],
    "chestplate": ["M M", "MLM", "MLM"],
    "leggings": ["MMM", "M M", "L L"],
    "boots": ["M M", "M M", "L L"],
}

# Tools need a binding (B) around the stick (S)
TOOL_TIERS = [("wooden", "#minecraft:planks", STRING), ("stone", "#minecraft:stone_tool_materials", STRING)] + [
    (t, m, LEATHER) for t, m in HIGH_TIERS
]
TOOL_PATTERNS = {
    "sword": [" M ", " M ", "BS "],
    "pickaxe": ["MMM", "BSB", " S "],
    "axe": ["MM ", "MSB", "BS "],
    "shovel": [" M ", "BSB", " S "],
    "hoe": ["MM ", "BSB", " S "],
}

# Chainmail has no vanilla recipe, so these get new IDs
CHAINMAIL_KEY = {"N": "minecraft:iron_nugget", "C": "minecraft:chain", "S": STRING}
CHAINMAIL_PATTERNS = {
    "helmet": ["NNN", "CSC"],
    "chestplate": ["N N", "CSC", "NNN"],
    "leggings": ["NNN", "CSC", "N N"],
    "boots": ["N N", "CSC"],
}

# ---------------------------------------------------------------- metal parts
HAMMER = "#forge:hammer"
METALS = [
    ("iron", "#forge:ingots/iron"),
    ("gold", "#forge:ingots/gold"),
    ("copper", "#forge:ingots/copper"),
    ("diamond", "#forge:gems/diamond"),
]

# ---------------------------------------------------------------- item tags
# (tag, values). Entries that may not exist are written as {"id": ..., "required": false}.
ITEM_TAGS = {
    # Normalises the hammer tags of other mods into one tag for the metal part recipes
    "forge:hammer": [
        {"id": "#forge:hammers", "required": False},
        {"id": "#forge:tools/hammers", "required": False},
        {"id": "#c:tools/hammers", "required": False},
        {"id": "#c:hammers", "required": False},
        {"id": "#c:hammer", "required": False},
    ],
    "minecraft:brewing_stand_fuel": ["minecraft:charcoal", "minecraft:coal"],
    "notreepunching:weak_saws": ["minecraft:wooden_axe", "minecraft:stone_axe"],
    "minecraft:animal_fat": ["butchery:animal_fat"],
}


def ing(s):
    """'#tag' or 'item' -> ingredient object."""
    return {"tag": s[1:]} if s.startswith("#") else {"item": s}


def result(item, count=1):
    r = {"item": item}
    if count > 1:
        r["count"] = count
    return r


def shaped(out, pattern, key, count=1):
    return {
        "type": "minecraft:crafting_shaped",
        "pattern": pattern,
        "key": {k: ing(v) for k, v in key.items() if any(k in row for row in pattern)},
        "result": result(out, count),
    }


def shapeless(out, ingredients, count=1):
    return {"type": "minecraft:crafting_shapeless", "ingredients": [ing(i) for i in ingredients], "result": result(out, count)}


def cooking(kind, out, ingredient, xp, time):
    return {"type": f"minecraft:{kind}", "ingredient": ing(ingredient), "result": out, "experience": xp, "cookingtime": time}


def tool_damaging(recipe, tool):
    """NoTreePunching wrapper: damages `tool` instead of consuming it (KubeJS damageIngredient)."""
    kind = "shaped" if recipe["type"] == "minecraft:crafting_shaped" else "shapeless"
    return {"type": f"notreepunching:tool_damaging_{kind}", "recipe": recipe, "tool": ing(tool)}


def build():
    """Return {resource id: json} for every recipe, plus tags keyed as ('tag', id)."""
    out = {}

    for rid in DISABLED:
        out[rid] = {"conditions": [{"type": "forge:false"}]}

    # Armor and tools override the vanilla recipe IDs in place
    for tier, material, lining in ARMOR_TIERS:
        for piece, pattern in ARMOR_PATTERNS.items():
            item = f"minecraft:{tier}_{piece}"
            out[item] = shaped(item, pattern, {"M": material, "L": lining})
    for tier, material, binding in TOOL_TIERS:
        for tool, pattern in TOOL_PATTERNS.items():
            item = f"minecraft:{tier}_{tool}"
            out[item] = shaped(item, pattern, {"M": material, "S": "minecraft:stick", "B": binding})
    for piece, pattern in CHAINMAIL_PATTERNS.items():
        item = f"minecraft:chainmail_{piece}"
        out[f"winterheart:equipment/chainmail_{piece}"] = shaped(item, pattern, CHAINMAIL_KEY)

    # Metal parts: ingot -> plate -> rods -> ring / bolts -> screw, plates + ring -> gear
    for metal, base in METALS:
        p = {part: f"winterheart:{metal}_{part}" for part in ("plate", "rod", "ring", "bolt", "screw", "gear")}
        c = f"winterheart:crafting/{metal}"
        out[f"{c}_plate_from_hammer"] = tool_damaging(shapeless(p["plate"], [base, HAMMER]), HAMMER)
        out[f"{c}_rods_from_plate"] = tool_damaging(shapeless(p["rod"], [p["plate"], HAMMER], 2), HAMMER)
        out[f"{c}_ring_from_rod"] = tool_damaging(shapeless(p["ring"], [p["rod"], p["rod"], HAMMER]), HAMMER)
        out[f"{c}_bolts_from_rod"] = tool_damaging(shapeless(p["bolt"], [p["rod"], HAMMER], 2), HAMMER)
        out[f"{c}_screw_from_bolt"] = tool_damaging(shapeless(p["screw"], [p["bolt"], HAMMER]), HAMMER)
        out[f"{c}_gear_from_plates_and_ring"] = tool_damaging(
            shaped(p["gear"], ["BPB", "PRP", "BHB"], {"P": p["plate"], "R": p["ring"], "B": p["bolt"], "H": HAMMER}),
            HAMMER,
        )

    # Early brewing stand from metal parts (overrides vanilla's blaze rod recipe)
    out["minecraft:brewing_stand"] = shaped(
        "minecraft:brewing_stand",
        [" I ", "CRC", "RSR"],
        {"I": "winterheart:iron_rod", "C": "minecraft:copper_ingot", "R": "winterheart:gold_ring", "S": "minecraft:cobblestone"},
    )

    # Gunpowder from saltpeter, sulfur and coal
    out["winterheart:gunpowder_from_saltpeter"] = shapeless(
        "minecraft:gunpowder", ["winterheart:saltpeter"] * 6 + ["butchery:sulfur"] + ["#minecraft:coals"] * 2, 16
    )

    # Leaching rich soil with purified water; the soil turns into dirt (needs the core mod's recipe type)
    leach = shapeless(
        "winterheart:crude_nitrate_bottle",
        ["farmersdelight:rich_soil"] + ["legendarysurvivaloverhaul:purified_water_bottle"] * 4,
        4,
    )
    leach["type"] = "winterheart:shapeless_with_remainders"
    leach["remainders"] = {"farmersdelight:rich_soil": "minecraft:dirt"}
    out["winterheart:crude_nitrate_from_rich_soil"] = leach

    # Boiling the potassium nitrate solution down to saltpeter crystals
    out["winterheart:saltpeter_from_smelting"] = cooking(
        "smelting", "winterheart:saltpeter", "winterheart:potassium_nitrate_bottle", 0.2, 200
    )

    # Logs -> charcoal on a campfire
    out["winterheart:charcoal_from_campfire_cooking"] = cooking(
        "campfire_cooking", "minecraft:charcoal", "#minecraft:logs", 0, 600
    )

    # Moss clump -> sponge
    out["winterheart:sponge_from_smelting_moss_clump"] = cooking(
        "smelting", "minecraft:sponge", "immersive_weathering:moss_clump", 0.1, 200
    )

    for tag, values in ITEM_TAGS.items():
        out[("tag", tag)] = {"replace": False, "values": values}

    return out


def path_for(key):
    if isinstance(key, tuple):
        ns, name = key[1].split(":", 1)
        return PACK / "data" / ns / "tags/items" / f"{name}.json"
    ns, name = key.split(":", 1)
    return PACK / "data" / ns / "recipes" / f"{name}.json"


def clean():
    removed = 0
    for f in (PACK / "data").rglob("*.json") if (PACK / "data").exists() else []:
        try:
            if json.loads(f.read_text()).get("__comment__") == MARKER:
                f.unlink()
                removed += 1
        except (json.JSONDecodeError, AttributeError):
            pass
    # drop directories left empty
    for d in sorted((PACK / "data").rglob("*"), reverse=True) if (PACK / "data").exists() else []:
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()
    return removed


def main():
    removed = clean()
    files = build()
    for key, data in files.items():
        f = path_for(key)
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(json.dumps({"__comment__": MARKER, **data}, indent=2) + "\n")
    print(f"removed {removed}, wrote {len(files)} files under {PACK.relative_to(PACK.parents[3])}")


if __name__ == "__main__":
    main()
