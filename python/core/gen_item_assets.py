#!/usr/bin/env python3
"""Generate the item models and en_us.json of the core mod (mod-src/winterheart).

    python3 python/core/gen_item_assets.py

Item textures come from python/core/metal_parts.py (metal parts) or are hand-drawn PNGs next to them.
Add a new simple item to ITEMS (and to ModItems.java), run this, done. Lang entries that aren't items go in EXTRA_LANG.
The guide book and lost page have no model here: the book's models are written by tools/guide_editor into the
winterheart_assets resource pack, and the lost page uses a vanilla texture.
"""
import json
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "mod-src/winterheart/src/main/resources/assets/winterheart"
MARKER = "Generated by python/core/gen_item_assets.py. Edit the script, not this file."

METALS = ["copper", "iron", "gold", "diamond"]
PARTS = ["plate", "rod", "ring", "gear", "bolt", "screw"]

# item id -> (display name, tooltip or None). Tooltips use the § colour codes' grey default, no codes needed.
ITEMS = {f"{m}_{p}": (f"{m.title()} {p.title()}", None) for m in METALS for p in PARTS}
ITEMS.update({
    "saltpeter": ("Saltpeter Crystals", "Potassium Nitrate (KNO₃). Vital for gunpowder and fertilizers."),
    "crude_nitrate_bottle": ("Crude Nitrate Solution", "Unrefined leachate extracted from nitrate-rich earth."),
    "potassium_nitrate_bottle": ("Potassium Nitrate Solution", "Filtered with wood ash to convert calcium nitrate into potassium nitrate."),
})

# Items whose model is not item/generated with textures/item/<id>.png
NO_MODEL = {"guide_book", "lost_page"}

# lost_page uses a vanilla texture, written here as its model
VANILLA_TEXTURE = {"lost_page": "minecraft:item/map"}

EXTRA_LANG = {
    "item.winterheart.guide_book": "Empty Guide Book",
    "item.winterheart.lost_page": "Lost Page",
    "effect.winterheart.limb_poising": "Limb Poising",
    "biome.winterheart.spawn_clearing": "Home",
}


def main():
    (RES / "models/item").mkdir(parents=True, exist_ok=True)
    for old in (RES / "models/item").glob("*.json"):
        if json.loads(old.read_text()).get("_generated_by") == MARKER:
            old.unlink()
    for item in ITEMS:
        model = {"_generated_by": MARKER, "parent": "item/generated", "textures": {"layer0": f"winterheart:item/{item}"}}
        (RES / f"models/item/{item}.json").write_text(json.dumps(model, indent=2) + "\n")
    for item, texture in VANILLA_TEXTURE.items():
        model = {"_generated_by": MARKER, "parent": "item/generated", "textures": {"layer0": texture}}
        (RES / f"models/item/{item}.json").write_text(json.dumps(model, indent=2) + "\n")

    lang = {}
    for item, (name, tip) in ITEMS.items():
        lang[f"item.winterheart.{item}"] = name
        if tip:
            lang[f"item.winterheart.{item}.tooltip"] = tip
    lang.update(EXTRA_LANG)
    (RES / "lang").mkdir(parents=True, exist_ok=True)
    (RES / "lang/en_us.json").write_text(json.dumps(lang, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {len(ITEMS) + len(VANILLA_TEXTURE)} item models and {len(lang)} lang entries")


if __name__ == "__main__":
    main()
